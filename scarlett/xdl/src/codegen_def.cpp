#include "codegen_def.hpp"

#include <algorithm>
#include <sstream>
#include <vector>

#include "layout.hpp"

namespace scarlett::xdl::compiler {

std::string generate_def_file(const Module& mod, VersionSpec target_abi, uint32_t target_flags) {
    std::ostringstream out;
    out << "; Auto-generated by scarlett-xdl from " << mod.source_path << "\n";
    out << "; Target ABI: " << target_abi.to_string() << "\n";
    out << "LIBRARY \"" << mod.dll_name << "\"\n";
    out << "EXPORTS\n";

    /* Sort ordinal exports first by ordinal, then named exports in declaration order */
    std::vector<const ExportDecl*> ordinal_exports;
    std::vector<const ExportDecl*> named_exports;

    for (const auto& ex : mod.exports) {
        const VersionSpec eff_abi = ex.attrs.force_abi.value_or(target_abi);
        if (!is_active_in_abi(ex.attrs, eff_abi, target_flags)) {
            continue;
        }
        if (ex.attrs.ordinal.has_value()) {
            ordinal_exports.push_back(&ex);
        } else {
            named_exports.push_back(&ex);
        }
    }

    std::sort(ordinal_exports.begin(), ordinal_exports.end(),
              [](const ExportDecl* a, const ExportDecl* b) {
                  return *a->attrs.ordinal < *b->attrs.ordinal;
              });

    for (const auto* ex : ordinal_exports) {
        out << "    " << ex->name << " @" << *ex->attrs.ordinal << "\n";
    }
    for (const auto* ex : named_exports) {
        out << "    " << ex->name << "\n";
    }

    return out.str();
}

} /* namespace scarlett::xdl::compiler */
